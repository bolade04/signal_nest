"""Project Phase 5 CF-2 (W21): privacy of the 5C tables, per operator decision O-6.

Built on the P6-PRIV-1 world (``_privacy_support``) with the CF-1 helpers: each test adds, in
organization A, a brief and a draft generated by CAROL with its content review and DAVE's
approval of the draft, and in B a brief and draft by BOB.

* **Account deletion (CAROL).** Her draft is kept; its ``created_by_snapshot`` becomes
  ``"[erased]"`` and ``created_by`` is nulled; the review and DAVE's decision on the draft are
  untouched; the receipt counts the anonymised draft and the independent verifier finds
  nothing (before the deletion it finds the draft).
* **Organization deletion (A).** A's drafts and their reviews are deleted with its scope;
  DAVE's approval of the draft is retained with ``draft_id`` cleared (the verifier requires
  it); B's draft is untouched; the verifier passes.
* **Account export.** CAROL's export lists the drafts she generated — ids, version, channel
  and her own snapshot — never the generated text, provenance or the usage-ledger link, and
  never another account's drafts.
* **Inventory.** ``creative_drafts`` is collected data with no retention class (a dependent
  of the brief); ``content_reviews`` is a compliance record with no retention class that
  cascades with its draft. No new retention class or duration.
"""

