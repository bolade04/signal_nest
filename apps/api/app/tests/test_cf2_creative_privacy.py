DRAFT_TEXT = "Spring offer: book this week"


@pytest.fixture
def env(tmp_path) -> Iterator[PrivacyEnv]:
    with privacy_world(tmp_path / "cf2-privacy.db") as e:
        yield e


def _draft(row_id: str, *, org: str, ws: str, brief: str, tag: str, author: str) -> dict:
    return dict(
        id=row_id, organization_id=org, workspace_id=ws, brief_id=brief,
        opportunity_id=f"{tag}-opp", draft_version=1, channel="email", headline="Spring",
        body=DRAFT_TEXT, call_to_action="Book", prompt_name="generate_creative",
        prompt_version="1.0.0", model_identifier="mock", input_hash="0" * 64,
        is_simulated=True, input_tokens=120, output_tokens=80, estimated_cost_usd=0,
        created_by=author, created_by_snapshot=_snapshot(author),
    )


def _add_creative_rows(env: PrivacyEnv) -> None:
    with env.engine.begin() as conn:
        conn.execute(
            insert(RecommendationBrief.__table__),
            [
                _brief("cf2-brief-a", ws=WS_A, org=ORG_A, tag="a1", author=CAROL),
                _brief("cf2-brief-b", ws=WS_B, org=ORG_B, tag="b1", author=BOB),
            ],
        )
        conn.execute(
            insert(CreativeDraft.__table__),
            [
                _draft("cf2-draft-a", org=ORG_A, ws=WS_A, brief="cf2-brief-a", tag="a1",
                       author=CAROL),
                _draft("cf2-draft-b", org=ORG_B, ws=WS_B, brief="cf2-brief-b", tag="b1",
                       author=BOB),
            ],
        )
        conn.execute(
            insert(ContentReview.__table__).values(
                id="cf2-review-a", organization_id=ORG_A, workspace_id=WS_A,
                draft_id="cf2-draft-a", draft_version=1, risk_level="low", is_blocked=False,
                findings=[], warnings=[], blocked_claim_ids=[], required_disclaimers=[],
                disclaimers_resolved=True, passed=True,
            )
        )
        conn.execute(
            insert(Approval.__table__).values(
                id="cf2-appr-dave", organization_id=ORG_A, workspace_id=WS_A,
                subject_type="creative_draft", subject_id="cf2-draft-a", subject_version=1,
                draft_id="cf2-draft-a", decision="approved", decision_seq=1, decided_by=DAVE,
                decided_by_snapshot=_snapshot(DAVE), decided_role="reviewer",
                is_simulated=False,
            )
        )


def test_account_deletion_keeps_the_draft_and_clears_what_names_the_account(env):
    _add_creative_rows(env)
    with env.session() as s:
        before = verify_subject_erased(s, user_id=CAROL, email=EMAIL[CAROL])
    assert "creative_drafts" in {f.table for f in before.reference_findings}
    assert "creative_drafts" in {f.table for f in before.content_findings}
    review_before = _by_id(env, ContentReview)["cf2-review-a"]
    approval_before = _by_id(env, Approval)["cf2-appr-dave"]
    bob_before = _by_id(env, CreativeDraft)["cf2-draft-b"]

    r = env.client.post(
        f"{API}/account/delete",
        headers=env.auth(CAROL),
        json={"current_password": PASSWORD, "confirmation": "DELETE"},
    )

    assert r.status_code == 200, r.text
    anonymised = r.json()["counts"]["anonymised"]
    assert anonymised["creative_drafts"] == 1
    assert anonymised["recommendation_briefs"] == 1
    draft = _by_id(env, CreativeDraft)["cf2-draft-a"]
    assert (draft["created_by"], draft["created_by_snapshot"]) == (None, ERASED_ACTOR_SNAPSHOT)
    assert draft["body"] == DRAFT_TEXT and draft["brief_id"] == "cf2-brief-a"  # kept (O-6)
    assert _by_id(env, ContentReview)["cf2-review-a"] == review_before
    assert _by_id(env, Approval)["cf2-appr-dave"] == approval_before
    assert _by_id(env, CreativeDraft)["cf2-draft-b"] == bob_before
    with env.session() as s:
        after = verify_subject_erased(s, user_id=CAROL, email=EMAIL[CAROL])
    assert after.verified, after.as_dict()


def test_organization_deletion_deletes_drafts_and_reviews_and_keeps_decisions(env):
    _add_creative_rows(env)
    bob_before = _by_id(env, CreativeDraft)["cf2-draft-b"]

    r = env.client.post(
        f"{API}/organizations/{ORG_A}/delete",
        headers=env.auth(ALICE),
        json={"current_password": PASSWORD, "confirm_organization_name": NAME[ORG_A]},
    )

    assert r.status_code == 200, r.text
    receipt = r.json()
    assert receipt["counts"]["deleted"]["creative_drafts"] == 1
    assert receipt["counts"]["deleted"]["content_reviews"] == 1
    assert set(_by_id(env, CreativeDraft)) == {"cf2-draft-b"}
    assert _by_id(env, CreativeDraft)["cf2-draft-b"] == bob_before
    assert _by_id(env, ContentReview) == {}
    decision = _by_id(env, Approval)["cf2-appr-dave"]  # a compliance record: retained
    assert (decision["draft_id"], decision["decided_by"], decision["note"]) == (None, None, None)
    assert decision["decided_by_snapshot"] == ERASED_ACTOR_SNAPSHOT
    assert (decision["subject_type"], decision["subject_id"]) == ("creative_draft", "cf2-draft-a")
    with env.session() as s:
        full = verify_organization_erased(
            s, organization_id=ORG_A, workspace_ids=WORKSPACES[ORG_A]
        )
    assert full.verified, full.as_dict()


def test_the_account_export_lists_the_accounts_drafts_only(env):
    _add_creative_rows(env)

    carol = env.client.get(f"{API}/account/export", headers=env.auth(CAROL))

    assert carol.status_code == 200, carol.text
    body = carol.json()
    assert [d["id"] for d in body["drafts_authored"]] == ["cf2-draft-a"]
    draft = body["drafts_authored"][0]
    assert set(draft) == {
        "id", "organization_id", "workspace_id", "brief_id", "draft_version", "channel",
        "created_by_snapshot", "created_at",
    }
    assert (draft["brief_id"], draft["draft_version"], draft["channel"]) == (
        "cf2-brief-a", 1, "email"
    )
    assert draft["created_by_snapshot"] == _snapshot(CAROL)
    assert DRAFT_TEXT not in json.dumps(body)  # model output: in the organization export
    assert _snapshot(BOB) not in json.dumps(body)
    for other in (ALICE, DAVE):
        mine = env.client.get(f"{API}/account/export", headers=env.auth(other)).json()
        assert mine["drafts_authored"] == []
    bob = env.client.get(f"{API}/account/export", headers=env.auth(BOB)).json()
    assert [d["id"] for d in bob["drafts_authored"]] == ["cf2-draft-b"]


def test_inventory_of_the_two_tables():
    assert TABLES["creative_drafts"].category is Category.COLLECTED
    assert TABLES["creative_drafts"].retention_class is None  # dependent rows
    assert TABLES["content_reviews"].category is Category.COMPLIANCE
    assert TABLES["content_reviews"].retention_class is None  # cascades with its draft
    # No new retention class and no duration was decided.
    assert len(RetentionClass) == 7
    settings = Settings(_env_file=None)
    assert all(getattr(settings, c.setting_name) is None for c in RetentionClass)
