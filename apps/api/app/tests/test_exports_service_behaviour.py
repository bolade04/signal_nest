def _context(s, world: CreativeWorld, ws: str, role: str = "owner") -> TenantContext:
    return TenantContext(
        user=s.get(User, world.users[role]),
        organization=s.get(Organization, world.org),
        workspace=s.get(Workspace, ws),
        role=Role(role),
    )


def test_the_service_flushes_only_the_caller_commits_or_rolls_back_both_rows(world):
    ws = export_workspace(world, "service")
    draft, approval = written_draft(world, ws)
    calls: list[dict] = []

    def recorder(db, **kwargs) -> int:
        calls.append({**kwargs, "recipient_user_ids": list(kwargs["recipient_user_ids"])})
        return 0

    with world.factory() as s:
        result = create_export(
            s, ctx=_context(s, world, ws), draft_id=draft["id"],
            export_format=ExportFormat.TEXT_PLAIN, emitter=recorder, settings=get_settings(),
        )
        assert result.content == PLAIN
        assert s.get(Export, result.export.id) is not None  # flushed in this transaction
        assert world.row(Export, result.export.id) is None  # not committed
        assert audits(world, draft["id"]) == []
        s.rollback()
    assert world.count(Export, draft_id=draft["id"]) == 0 and audits(world, draft["id"]) == []

    with world.factory() as s:
        result = create_export(
            s, ctx=_context(s, world, ws), draft_id=draft["id"],
            export_format=ExportFormat.JSON, emitter=recorder, settings=get_settings(),
        )
        export_id = result.export.id
        s.commit()
    row = world.row(Export, export_id)
    assert row is not None and row["approval_id"] == approval["id"]
    assert [a["new_state"]["export_id"] for a in audits(world, draft["id"])] == [export_id]
    # Both calls went through the injected emitter, with this export as the subject.
    assert len(calls) == 2
    assert calls[1]["event_code"] == "export.completed"
    assert (calls[1]["organization_id"], calls[1]["workspace_id"], calls[1]["subject_id"]) == (
        world.org, ws, export_id,
    )


