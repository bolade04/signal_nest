def notifications_of(world: CreativeWorld, export_id: str) -> list[dict]:
    return world.rows(Notification, subject_id=export_id)


def test_export_completed_reaches_the_author_and_the_approver_never_the_exporter(world):
    ws = export_workspace(world, "notified", notifications=True)
    draft, _approval = written_draft(world, ws)
    author, approver = world.users["marketer"], world.users["reviewer"]

    by_owner = export(world, ws, draft["id"], "text/plain", role="owner")
    assert by_owner.status_code == 201, by_owner.text
    rows = notifications_of(world, by_owner.json()["id"])
    assert sorted(r["user_id"] for r in rows) == sorted([author, approver])
    assert {(r["event_code"], r["organization_id"], r["workspace_id"]) for r in rows} == {
        ("export.completed", world.org, ws)
    }
    assert all(r["read_at"] is None and r["deleted_at"] is None for r in rows)

    by_author = export(world, ws, draft["id"], "json", role="marketer")
    assert by_author.status_code == 201, by_author.text
    assert [r["user_id"] for r in notifications_of(world, by_author.json()["id"])] == [approver]


