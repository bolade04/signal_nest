def _override(world: CreativeWorld, ws: str, capability: str, enabled: bool = True) -> None:
    """A workspace override for ``capability`` (the global flag stays off)."""
    with world.session() as s:
        existing = s.scalar(
            select(WorkspaceCapabilityOverride).where(
                WorkspaceCapabilityOverride.workspace_id == ws,
                WorkspaceCapabilityOverride.capability == capability,
            )
        )
        if existing is not None:
            s.delete(existing)
            s.flush()
        s.add(
            WorkspaceCapabilityOverride(
                organization_id=world.org_of(ws), workspace_id=ws, capability=capability,
                enabled=enabled, set_by_user_id=world.owner_id(ws), reason="5E-W2 test",
            )
        )


def export_workspace(world: CreativeWorld, name: str, *, notifications: bool = False) -> str:
    """A fresh workspace with generation and export on (and O-12(B) when asked)."""
    ws = world.workspace(name)
    _override(world, ws, "content_export")
    if notifications:
        _override(world, ws, "notifications_analytics")
    return ws


def _approve(world: CreativeWorld, ws: str, draft_id: str) -> dict:
    """The organization's reviewer approves version 1 through the 5B decision route."""
    r = world.send(
        "POST", f"/workspaces/{ws}/drafts/{draft_id}/approvals", "reviewer",
        {"decision": "approved", "subject_version": 1},
    )
    assert r.status_code == 201, r.text
    return r.json()


def approved_brief(world: CreativeWorld, ws: str) -> str:
    """A brief whose version the reviewer approved (item 38: export requires it), checked
    with the rule the export service applies."""
    brief_id = world.seed_brief(ws, approved=True)
    with world.session() as s:
        assert brief_is_approved(s, s.get(RecommendationBrief, brief_id))
    return brief_id


def generated_draft(world: CreativeWorld, ws: str) -> tuple[dict, dict]:
    """A draft the mock generated from an approved brief (the marketer asked), then approved."""
    brief_id = approved_brief(world, ws)
    assert world.generated(brief_id, ws=ws)["status"] == "succeeded"
    [draft] = world.rows(CreativeDraft, brief_id=brief_id)
    return draft, _approve(world, ws, draft["id"])


def written_draft(
    world: CreativeWorld,
    ws: str,
    *,
    headline: str | None = HEADLINE,
    body: str = BODY,
    call_to_action: str | None = CTA,
    is_simulated: bool = False,
) -> tuple[dict, dict]:
    """A draft with exact text, written as the 5C service writes one (marketer-authored, its
    passed review, the brief's captured jurisdiction), then approved through the route."""
    brief_id = approved_brief(world, ws)
    draft_id = f"dr{uuid.uuid4().hex[:12]}"
    with world.session() as s:
        brief = s.get(RecommendationBrief, brief_id)
        author = s.get(User, world.users["marketer"])
        scoped = {"organization_id": brief.organization_id, "workspace_id": brief.workspace_id}
        s.add(CreativeDraft(
            id=draft_id, brief_id=brief_id, opportunity_id=brief.opportunity_id,
            draft_version=1, channel="email", headline=headline, body=body,
            call_to_action=call_to_action, prompt_name="generate_creative",
            prompt_version="1.0.0", model_identifier="mock-1", input_hash="0" * 64,
            is_simulated=is_simulated, input_tokens=1, output_tokens=1, estimated_cost_usd=0,
            created_by=author.id,
            created_by_snapshot=actor_snapshot(
                user_id=author.id, full_name=author.full_name, email=author.email
            ),
            jurisdiction_code=brief.jurisdiction_code, **scoped,
        ))
        s.flush()
        s.add(ContentReview(
            draft_id=draft_id, draft_version=1, risk_level="low", is_blocked=False,
            findings=[], warnings=[], blocked_claim_ids=[], required_disclaimers=[],
            disclaimers_resolved=True, passed=True, jurisdiction_code=brief.jurisdiction_code,
            **scoped,
        ))
    return world.row(CreativeDraft, draft_id), _approve(world, ws, draft_id)


def export(world: CreativeWorld, ws: str, draft_id: str, fmt: str, role: str = "owner"):
    return world.send("POST", f"/workspaces/{ws}/drafts/{draft_id}/exports", role, {"format": fmt})


def history(world: CreativeWorld, ws: str, draft_id: str, role: str = "owner", query: str = ""):
    return world.send("GET", f"/workspaces/{ws}/drafts/{draft_id}/exports{query}", role)


def snapshot_of(world: CreativeWorld, role: str) -> str:
    user = world.row(User, world.users[role])
    return actor_snapshot(user_id=user["id"], full_name=user["full_name"], email=user["email"])


def audits(world: CreativeWorld, draft_id: str) -> list[dict]:
    return world.rows(AuditLog, entity_id=draft_id, action=EXPORTED)


def assert_recorded(world: CreativeWorld, ws: str, draft: dict, approval: dict, body: dict,
                    fmt: str, role: str) -> None:
    """The answer, its exports row and its one audit row agree, field by field."""
    assert set(body) == ITEM_KEYS | {"content"}
    row = world.row(Export, body["id"])  # read through another connection: committed
    assert row is not None
    expected = {
        "organization_id": world.org,
        "workspace_id": ws,
        "draft_id": draft["id"],
        "draft_version": draft["draft_version"],
        "approval_id": approval["id"],
        "format": fmt,
        "jurisdiction_code": draft["jurisdiction_code"],
        "exported_by": world.users[role],
        "exported_by_snapshot": snapshot_of(world, role),
        "is_simulated": draft["is_simulated"],
    }
    assert {key: row[key] for key in expected} == expected
    assert {key: body[key] for key in ITEM_KEYS - {"created_at"}} == {
        key: row[key] for key in ITEM_KEYS - {"created_at"}
    }
    [audit] = [a for a in audits(world, draft["id"]) if a["new_state"]["export_id"] == row["id"]]
    assert (audit["organization_id"], audit["workspace_id"], audit["actor_user_id"]) == (
        world.org, ws, world.users[role],
    )
    assert audit["entity_type"] == "creative_draft"
    assert audit["new_state"] == {
        "export_id": row["id"],
        "draft_version": row["draft_version"],
        "approval_id": row["approval_id"],
        "format": fmt,
        "jurisdiction_code": row["jurisdiction_code"],
        "is_simulated": row["is_simulated"],
    }


