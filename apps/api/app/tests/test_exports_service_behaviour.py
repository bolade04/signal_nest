def test_each_format_answers_the_approved_text_rendered_exactly(world):
    ws = export_workspace(world, "formats")
    draft, approval = written_draft(world, ws)
    contents = {}
    for fmt in FORMATS:
        r = export(world, ws, draft["id"], fmt)
        assert r.status_code == 201, r.text
        assert_recorded(world, ws, draft, approval, r.json(), fmt, "owner")
        contents[fmt] = r.json()["content"]

    assert contents["text/plain"] == PLAIN
    assert contents["text/markdown"] == MARKDOWN
    document = {
        "draft_id": draft["id"],
        "draft_version": 1,
        "channel": "email",
        "jurisdiction_code": "US-TX",
        "is_simulated": False,
        "headline": HEADLINE,
        "body": BODY,
        "call_to_action": CTA,
    }
    assert json.loads(contents["json"]) == document
    assert contents["json"] == json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2)
    assert "café" in contents["json"]  # non-ASCII kept as written, not \u-escaped
    assert not any(text.endswith("\n") for text in contents.values())


def test_absent_blocks_are_left_out_of_every_format(world):
    ws = export_workspace(world, "body only")
    draft, _approval = written_draft(world, ws, headline=None, call_to_action=None,
                                     body="Only the body.")
    answers = {fmt: export(world, ws, draft["id"], fmt) for fmt in FORMATS}
    assert {fmt: r.status_code for fmt, r in answers.items()} == dict.fromkeys(FORMATS, 201)
    assert answers["text/plain"].json()["content"] == "Only the body."
    assert answers["text/markdown"].json()["content"] == "Only the body."
    document = json.loads(answers["json"].json()["content"])
    assert (document["headline"], document["body"], document["call_to_action"]) == (
        None, "Only the body.", None,
    )


def test_a_generated_draft_exports_its_stored_text_in_every_format(world):
    """The real chain: the mock's draft, generated by the job and approved by the reviewer."""
    ws = export_workspace(world, "generated")
    draft, approval = generated_draft(world, ws)
    blocks = [t for t in (draft["headline"], draft["body"], draft["call_to_action"]) if t]
    for fmt in FORMATS:
        r = export(world, ws, draft["id"], fmt, role="marketer")
        assert r.status_code == 201, r.text
        assert_recorded(world, ws, draft, approval, r.json(), fmt, "marketer")
        content = r.json()["content"]
        if fmt == "text/plain":
            assert content == "\n\n".join(blocks)
        elif fmt == "json":
            stored = json.loads(content)
            assert {k: stored[k] for k in ("headline", "body", "call_to_action")} == {
                k: draft[k] for k in ("headline", "body", "call_to_action")
            }
            assert stored["is_simulated"] is True and stored["jurisdiction_code"] == "US-TX"
        else:
            assert content.startswith("# ") == bool(draft["headline"])
    assert world.row(Export, r.json()["id"])["is_simulated"] is True  # the mock's draft


