"""Audited manual export: the success path (Project Phase 5E; lane 5E-W2's cross-authored test
of lane 5E-W1's export code).

Source: ``docs/project-phase-5e-notifications-analytics-export.md`` §2 (audited manual export)
and §4 exit criterion 3 ("the success path writes export + audit atomically"), the 5E §5 W2
row ("the export success path: three render formats, export history, and the atomic export +
audit write"), and the 5E interface sheet (P4 routes, P9 recipients). Behaviour only: every
refusal (role, capability, scope, jurisdiction, decision, review) is lane 5E-W4's
(``test_exports_*`` negatives), and none is asserted here.

The world is the 5C harness (:mod:`app.tests._creative_support`): a real HTTP app on SQLite with
foreign keys on, and the same world on a PostgreSQL database of its own migrated to head
(``TEST_POSTGRES_URL``; unset fails in CI and skips on a developer machine). Export and
O-12(B)'s notifications are opened per workspace by override rows, as an operator would; the
global flags stay off. Drafts are either generated by the mock provider through the real
generation job, or written as the 5C service writes them when a test needs exact text. Every
brief version is approved by the organization's reviewer first (operator ruling D-N4 item 38:
export, like a draft approval, requires the brief version's controlling decision to be
``approved``; that refusal is lane 5E-W4's), and every draft is then approved through the real
decision route.

What is proven:

1. **Three render formats** — each answers 201 with the record and the rendered text:
   ``text/plain`` is the stored blocks unchanged, one blank line apart; ``text/markdown`` is a
   level-one heading, then the body and call to action, with every Markdown syntax character of
   the text escaped and line breaks kept as hard breaks; ``json`` is one sorted, two-space
   indented object of the draft's identity and text, non-ASCII kept. Absent blocks are left out.
2. **The atomic write** — each export writes exactly one ``exports`` row (the draft's exact
   version, the controlling approval, the draft's captured jurisdiction, the exporter and their
   snapshot, the draft's simulation flag) and exactly one ``creative_draft.exported`` audit row
   naming it, committed together before the answer. :func:`create_export` itself only flushes:
   the caller's rollback leaves nothing, the caller's commit keeps both.
3. **export.completed** — written in the same transaction, through the injected emitter, to the
   draft's author and the approving reviewer and never to the exporter (P9), and only while
   O-12(B) is on for the workspace. A raising emitter rolls the export, its audit row and every
   notification back (a 500; nothing is written); the same export then succeeds.
4. **The export history** — the draft's exports, newest first (``created_at``, then ``id``,
   descending), without their text, paged, for every history role (item 32: owner, admin,
   marketer, reviewer, compliance reviewer).
"""

