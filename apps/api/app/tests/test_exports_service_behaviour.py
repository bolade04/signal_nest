def test_history_lists_the_drafts_exports_newest_first_without_text(world):
    ws = export_workspace(world, "history")
    draft, _approval = written_draft(world, ws)
    other, _ = written_draft(world, ws, body="Another draft.")
    made = []
    for fmt, role in zip(FORMATS, ("owner", "admin", "marketer"), strict=True):
        r = export(world, ws, draft["id"], fmt, role=role)
        assert r.status_code == 201, r.text
        made.append(r.json())
    assert export(world, ws, other["id"], "json").status_code == 201

    rows = world.rows(Export, draft_id=draft["id"])
    newest_first = [
        row["id"] for row in sorted(rows, key=lambda row: (row["created_at"], row["id"]),
                                    reverse=True)
    ]
    by_id = {m["id"]: m for m in made}
    for role in HISTORY_ROLES:
        h = history(world, ws, draft["id"], role)
        assert h.status_code == 200, (role, h.text)
        page = h.json()
        assert (page["total"], page["limit"], page["offset"]) == (3, 20, 0)
        assert [item["id"] for item in page["items"]] == newest_first, role
        for item in page["items"]:
            assert set(item) == ITEM_KEYS  # no rendered text in the history
            assert {k: item[k] for k in ITEM_KEYS - {"created_at"}} == {
                k: by_id[item["id"]][k] for k in ITEM_KEYS - {"created_at"}
            }
    snapshots = {item["exported_by_snapshot"] for item in history(world, ws, draft["id"])
                 .json()["items"]}
    assert snapshots == {snapshot_of(world, role) for role in ("owner", "admin", "marketer")}

    second = history(world, ws, draft["id"], query="?limit=1&offset=1").json()
    assert (second["total"], second["limit"], second["offset"]) == (3, 1, 1)
    assert [item["id"] for item in second["items"]] == newest_first[1:2]

    assert [item["draft_id"] for item in history(world, ws, other["id"]).json()["items"]] == [
        other["id"]
    ]


