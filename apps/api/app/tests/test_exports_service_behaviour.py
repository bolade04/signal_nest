def _send_with_emitter(world: CreativeWorld, ws: str, draft_id: str, emitter, fmt: str):
    """POST an export with the route's emitter dependency overridden (the injection seam)."""
    app.dependency_overrides[get_notification_emitter] = lambda: emitter
    try:
        _rate_limiter()._hits.clear()
        return TestClient(app, raise_server_exceptions=False).post(
            f"{API}/workspaces/{ws}/drafts/{draft_id}/exports",
            headers={"Authorization": f"Bearer {world.tokens['owner']}"},
            json={"format": fmt},
        )
    finally:
        app.dependency_overrides.pop(get_notification_emitter, None)


def test_the_route_writes_through_the_injected_emitter(world):
    ws = export_workspace(world, "injected", notifications=True)
    draft, _approval = written_draft(world, ws)
    calls: list[dict] = []

    def recorder(db, **kwargs) -> int:
        calls.append({**kwargs, "recipient_user_ids": list(kwargs["recipient_user_ids"])})
        return 0

    r = _send_with_emitter(world, ws, draft["id"], recorder, "text/plain")
    assert r.status_code == 201, r.text
    assert calls == [{
        "organization_id": world.org,
        "workspace_id": ws,
        "recipient_user_ids": [world.users["marketer"], world.users["reviewer"]],
        "event_code": "export.completed",
        "subject_id": r.json()["id"],
    }]
    # The recorder wrote nothing: no notification came from anywhere else.
    assert notifications_of(world, r.json()["id"]) == []


def test_a_raising_emitter_rolls_back_the_export_its_audit_and_every_notification(world):
    ws = export_workspace(world, "atomic", notifications=True)
    draft, _approval = written_draft(world, ws)
    notifications_before = world.count(Notification, workspace_id=ws)

    def raising(db, **kwargs) -> int:
        # Write as the real emitter would, then fail: the rows must not survive.
        emit_notifications(db, **kwargs)
        raise RuntimeError("notification store unavailable")

    r = _send_with_emitter(world, ws, draft["id"], raising, "text/plain")
    assert r.status_code == 500
    assert world.count(Export, draft_id=draft["id"]) == 0
    assert audits(world, draft["id"]) == []
    assert world.count(Notification, workspace_id=ws) == notifications_before

    retry = export(world, ws, draft["id"], "text/plain")
    assert retry.status_code == 201, retry.text
    assert world.count(Export, draft_id=draft["id"]) == 1 and len(audits(world, draft["id"])) == 1
    assert len(notifications_of(world, retry.json()["id"])) == 2


