    assert decide("rejected", reason_code="inaccurate").status_code == 201
    w.decide(brief_id, "approved")
    approved = decide("approved")
    assert approved.status_code == 201, approved.text
    assert [i["decision"] for i in w.send("GET", path, "reviewer").json()["items"]] == [
        "approved", "rejected"
    ]
