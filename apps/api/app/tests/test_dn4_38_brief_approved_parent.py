def test_through_the_routes_a_draft_of_a_revoked_brief_is_refused_409(
    http_world: CreativeWorld,
):
    w = http_world
    ws = w.workspace("item 38")
    brief_id = w.seed_brief(ws)  # approved
    assert w.generated(brief_id, ws=ws)["status"] == "succeeded"
    [draft] = w.rows(CreativeDraft, brief_id=brief_id)
    path = f"/workspaces/{ws}/drafts/{draft['id']}/approvals"

    def decide(decision: str, **extra):
        return w.send("POST", path, "reviewer",
                      {"decision": decision, "subject_version": 1, **extra})

    w.decide(brief_id, "revoked")
    refused = decide("approved")
    assert refused.status_code == 409, refused.text
