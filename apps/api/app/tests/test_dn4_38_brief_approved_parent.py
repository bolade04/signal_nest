# --------------------------------------------------------------------------- #
# PostgreSQL: a brief revocation racing a draft approval, and the lock order
# --------------------------------------------------------------------------- #
class _Runner(threading.Thread):
    def __init__(self, fn, *args, **kwargs):
        super().__init__(daemon=True)
        self._call = (fn, args, kwargs)
        self.result = None
        self.error: BaseException | None = None

    def run(self) -> None:  # pragma: no cover - exercised through join
        fn, args, kwargs = self._call
        try:
            self.result = fn(*args, **kwargs)
        except BaseException as exc:  # noqa: BLE001 - re-raised in the test thread
            self.error = exc

    def outcome(self, seconds: float = JOIN_SECONDS):
        self.join(seconds)
        assert not self.is_alive(), "a transaction did not finish"
        if self.error is not None:
            raise self.error
        return self.result


def _pid(s: Session) -> int:
    return s.execute(text("SELECT pg_backend_pid()")).scalar_one()


def _waiting(w: World, holder: int, *needles: str) -> tuple[list[dict], list[dict]]:
    """``(matching, seen)``: backends in a heavyweight-lock wait, and those blocked by
    ``holder`` whose statement contains every needle."""
    assert w.observer is not None
    with w.observer.connect() as c:
        seen = [dict(r) for r in c.execute(text(
            "SELECT pid, pg_blocking_pids(pid) AS blockers, wait_event, query"
            " FROM pg_stat_activity"
            " WHERE datname = current_database() AND wait_event_type = 'Lock'"
        )).mappings()]
    matching = [
        r for r in seen
        if holder in (r["blockers"] or []) and all(n in r["query"] for n in needles)
    ]
    return matching, seen


def _wait_for(observe, what: str):
    deadline = time.monotonic() + POLL_SECONDS
    seen = None
    while time.monotonic() < deadline:
        value, seen = observe()
        if value:
            return value
        time.sleep(0.05)
    raise AssertionError(f"timed out waiting for {what} after {POLL_SECONDS} s; last: {seen}")


def _draft_approval(w: World, draft_id: str, pid: list[int],
                    holding: threading.Event | None = None,
                    hold: threading.Event | None = None) -> tuple:
    """An approval of the draft; with ``holding``/``hold`` it flushes, signals and commits only
    when released."""
    with w.factory() as s:
        pid.append(_pid(s))
        try:
            approval = _decide_draft(s, draft_id, APPROVED)
        except (ConflictError, NotFoundError) as exc:
            s.rollback()
            return ("refused" if isinstance(exc, ConflictError) else "not_found", exc.message)
        if holding is not None:
            holding.set()
            assert hold is not None and hold.wait(JOIN_SECONDS)
        s.commit()
        return ("ok", approval.decision)


def _brief_decision(w: World, brief_id: str, decision: ApprovalDecision, pid: list[int],
                    holding: threading.Event | None = None,
                    hold: threading.Event | None = None) -> str:
    with w.factory() as s:
        pid.append(_pid(s))
        _decide_brief(s, brief_id, decision)
        if holding is not None:
            holding.set()
            assert hold is not None and hold.wait(JOIN_SECONDS)
        s.commit()
        return "ok"


def test_a_revocation_first_the_approval_waits_and_is_refused(pg: World):
    _commit_brief_decisions(pg, ((BRIEF1, APPROVED),))
    holding, hold, revoker = threading.Event(), threading.Event(), []
    revocation = _Runner(_brief_decision, pg, BRIEF1, REVOKED, revoker, holding, hold)
    revocation.start()
    assert holding.wait(JOIN_SECONDS), "the revocation never flushed"
    approver: list[int] = []
    approval = _Runner(_draft_approval, pg, DRAFT1, approver)
    approval.start()
    try:
        # The revocation holds the brief FOR UPDATE (its subject lock); the approval, holding
        # the draft, waits on the brief at step 5 instead of reading the uncommitted state.
        _wait_for(lambda: _waiting(pg, revoker[0], "recommendation_briefs", "FOR KEY SHARE"),
                  "the approval to wait on the brief row the revocation holds")
        time.sleep(0.3)
        assert approval.is_alive()
    finally:
        hold.set()
    assert revocation.outcome() == "ok"
    assert approval.outcome() == ("refused", BRIEF_NOT_APPROVED)  # it read the revocation
    assert _draft_history(pg, DRAFT1) == []


def test_an_approval_first_the_revocation_waits_until_it_has_committed(pg: World):
    _commit_brief_decisions(pg, ((BRIEF1, APPROVED),))
    holding, hold, approver = threading.Event(), threading.Event(), []
    approval = _Runner(_draft_approval, pg, DRAFT1, approver, holding, hold)
    approval.start()
    assert holding.wait(JOIN_SECONDS), "the approval never flushed"
    revoker: list[int] = []
    revocation = _Runner(_brief_decision, pg, BRIEF1, REVOKED, revoker)
    revocation.start()
    try:
        # The approval holds the brief FOR KEY SHARE until it commits; the revocation's subject
        # lock (FOR UPDATE) waits on it, so it cannot commit before the approval does.
        _wait_for(lambda: _waiting(pg, approver[0], "recommendation_briefs", "FOR UPDATE"),
                  "the revocation to wait on the brief row the approval holds")
        time.sleep(0.3)
        assert revocation.is_alive()
        with pg.factory() as s:  # nothing of the revocation is visible yet
            assert creative_service.brief_is_approved(s, s.get(RecommendationBrief, BRIEF1))
    finally:
        hold.set()
    assert approval.outcome() == ("ok", "approved")
    assert revocation.outcome() == "ok"  # then it completes: no deadlock, no timeout
    assert _draft_history(pg, DRAFT1) == [("approved", 1)]  # the approval stands
    _assert_brief_not_approved(_refused(pg, DRAFT1))  # and nothing can be approved after it
    assert _draft_history(pg, DRAFT1) == [("approved", 1)]


def test_generating_a_revision_never_deadlocks_with_approving_its_parent(pg: World):
    """Generation locks the brief ``FOR UPDATE`` (version allocation), then its new row's
    foreign key takes ``KEY SHARE`` on the parent draft. The approval holds that draft ``NO KEY
    UPDATE``, which admits it, and waits on the brief: no cycle. (A draft held ``FOR UPDATE``
    would make one: 40P01.)"""
    _commit_brief_decisions(pg, ((BRIEF1, APPROVED),))
    locked, go, generator = threading.Event(), threading.Event(), []

    def generate() -> int:
        with pg.factory() as s:
            generator.append(_pid(s))
            brief = s.get(RecommendationBrief, BRIEF1)
            version = creative_service._next_version(s, brief)  # the brief FOR UPDATE
            locked.set()
            assert go.wait(JOIN_SECONDS)
            parent = s.get(CreativeDraft, DRAFT1)
            s.add(CreativeDraft(
                id="draft-d38-revision", organization_id=ORG, workspace_id=WS,
                brief_id=BRIEF1, opportunity_id=parent.opportunity_id, draft_version=version,
                parent_draft_id=DRAFT1, channel="email", body="A revision.",
                prompt_name="generate_creative", prompt_version="1.0.0",
                model_identifier="mock-model", input_hash="1" * 64, is_simulated=True,
                input_tokens=1, output_tokens=1, estimated_cost_usd=0,
                created_by=parent.created_by, created_by_snapshot=parent.created_by_snapshot,
            ))
            s.flush()  # the parent's foreign-key KEY SHARE
            s.commit()
            return version

    generation = _Runner(generate)
    generation.start()
    assert locked.wait(JOIN_SECONDS), "generation never locked the brief"
    approver: list[int] = []
    approval = _Runner(_draft_approval, pg, DRAFT1, approver)
    approval.start()
    try:
        _wait_for(lambda: _waiting(pg, generator[0], "recommendation_briefs", "FOR KEY SHARE"),
                  "the approval to wait on the brief row generation holds")
    finally:
        go.set()
    assert generation.outcome() == 2  # outcome() re-raises a 40P01
    assert approval.outcome() == ("ok", "approved")


def test_the_opportunity_purge_never_deadlocks_with_an_approval(pg: World, monkeypatch):
    """The retention purge's foreign-key walk deletes a brief's drafts before the brief. Paused
    right after the drafts are deleted, it holds the draft; the approval waits on the draft (step
    4) holding no brief lock, so the purge deletes the brief, commits, and the approval finds the
    draft gone (404). (A brief lock taken before the draft would make a cycle: 40P01.)"""
    _commit_brief_decisions(pg, ((BRIEF1, APPROVED),))
    deleted, resume, purger_pid = threading.Event(), threading.Event(), []
    real = erasure.delete_rows

    def delete_rows(db, table, ids):
        counts = real(db, table, ids)
        if table.name == "creative_drafts" and not deleted.is_set():
            deleted.set()
            assert resume.wait(JOIN_SECONDS)
        return counts

    monkeypatch.setattr(erasure, "delete_rows", delete_rows)

    def purge() -> dict:
        with pg.factory() as s:
            purger_pid.append(_pid(s))
            batch = purge_batch(s, RetentionClass.OPPORTUNITIES,
                                datetime.now(UTC) + timedelta(days=1), batch_size=10,
                                workspace_id=WS)
            s.commit()
            return dict(batch.counts.deleted)

    purger = _Runner(purge)
    purger.start()
    assert deleted.wait(JOIN_SECONDS), "the purge never deleted the drafts"
    approver: list[int] = []
    approval = _Runner(_draft_approval, pg, DRAFT1, approver)
    approval.start()
    try:
        _wait_for(lambda: _waiting(pg, purger_pid[0], "creative_drafts"),
                  "the approval to wait on the draft the purge deleted")
    finally:
        resume.set()
    deleted_counts = purger.outcome()
    assert (deleted_counts["recommendation_briefs"], deleted_counts["creative_drafts"]) == (2, 2)
    assert approval.outcome() == ("not_found", svc.DRAFT_NOT_FOUND)


def test_account_erasure_holding_the_brief_never_deadlocks_with_an_approval(pg: World):
    """Account erasure updates the author's briefs, then their drafts (``NO KEY UPDATE``
    each). Paused between the two, it holds the brief: the approval's ``KEY SHARE`` admits that,
    so the approval completes without waiting, and the erasure then updates the draft. (A
    ``FOR SHARE`` brief lock would wait, and the erasure would then wait on the approval's
    draft: 40P01.)"""
    _commit_brief_decisions(pg, ((BRIEF1, APPROVED),))
    briefed, go = threading.Event(), threading.Event()

    def erase() -> dict:
        with pg.factory() as s:
            conn = s.connection()

            def pause(conn, cursor, statement, parameters, context, executemany):
                if statement.lstrip().upper().startswith("UPDATE CREATIVE_DRAFTS"):
                    if not briefed.is_set():
                        briefed.set()
                        assert go.wait(JOIN_SECONDS)

            event.listen(conn, "before_cursor_execute", pause)
            counts = anonymise_phase5_records_for_subject(s, user_id=AUTHOR, email=None)
            s.commit()
            return dict(counts)

    eraser = _Runner(erase)
    eraser.start()
    assert briefed.wait(JOIN_SECONDS), "the erasure never reached the drafts"
    approver: list[int] = []
    approval = _Runner(_draft_approval, pg, DRAFT1, approver)
    approval.start()
    try:
        approval.join(15.0)
        finished = not approval.is_alive()
    finally:
        go.set()
    assert finished, "the approval waited on the brief the erasure holds"
    assert approval.outcome() == ("ok", "approved")
    assert eraser.outcome() == {"recommendation_briefs": 2, "creative_drafts": 2}


