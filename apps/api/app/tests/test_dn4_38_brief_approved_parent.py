def test_an_approval_recorded_while_the_brief_was_approved_stands_after_it_is_revoked(world):
    """The ruling's "preserve historical decisions": the brief's revocation re-evaluates nothing.
    The draft's approval and its audit row stay exactly as recorded and the drafts view still
    shows it as the controlling decision; only a new approval is refused."""
    _commit_brief_decisions(world, ((BRIEF1, APPROVED),))
    with world.factory() as s:
        standing = _decide_draft(s, DRAFT1, APPROVED).id
        s.commit()
    before = _snapshot(world)
    _commit_brief_decisions(world, ((BRIEF1, REVOKED),))
    after = _snapshot(world)
    for table, rows in before.items():  # every row recorded before is byte-equal afterwards
        assert set(rows) <= set(after[table]), table
    added = {t: [json.loads(r) for r in after[t] if r not in before[t]] for t in after}
    assert [(a["subject_type"], a["subject_id"], a["decision"]) for a in added["approvals"]] == [
        ("recommendation_brief", BRIEF1, "revoked")
    ]
    assert [(a["action"], a["entity_id"]) for a in added["audit_logs"]] == [
        ("approval.revoked", BRIEF1)
    ]
    assert all(not added[t] for t in ("recommendation_briefs", "creative_drafts",
                                      "content_reviews"))
    with world.factory() as s:
        draft = s.get(CreativeDraft, DRAFT1)
        page = svc.list_draft_decisions(s, draft=draft)  # what the drafts view lists
        assert [(a.id, a.decision) for a in page.items] == [(standing, "approved")]
        # What the 5E export will ask before exporting it (interface sheet P6).
        assert draft_approval_refusal(s, draft) == "brief_not_approved"
    _assert_brief_not_approved(_refused(world, DRAFT1))  # approving it again is refused
    assert _snapshot(world) == after


def test_the_brief_lock_follows_the_draft_lock_and_precedes_the_read(world: World):
    """Statement order inside an approval ("Lock order" steps 3 to 5 in ``approvals.service``):
    the membership, the draft row, the brief row, the brief's controlling decision, then
    ``max(decision_seq)``. A rejection takes no brief lock."""
    _commit_brief_decisions(world, ((BRIEF1, APPROVED),))
    seen: list[str] = []

    def record(conn, cursor, statement, parameters, context, executemany):
        seen.append(" ".join(statement.split()).lower())

    event.listen(world.engine, "before_cursor_execute", record)
    try:
        for decision in (APPROVED, REJECTED):
            with world.factory() as s:
                ctx, draft = _ctx(s, DECIDER), s.get(CreativeDraft, DRAFT1)
                s.get(RecommendationBrief, BRIEF1)  # loaded, as the request has its rows
                seen.clear()
                svc.record_draft_decision(s, ctx=ctx, draft=draft, decision=decision,
                                          subject_version=1, reason_code=REASON[decision])
                s.commit()
            if decision is APPROVED:
                approve = list(seen)
    finally:
        event.remove(world.engine, "before_cursor_execute", record)

    def first(statements, prefix) -> int:
        return next(i for i, q in enumerate(statements) if q.startswith(prefix))

    member = first(approve, "select organization_members.role")
    draft_lock = first(approve, "select creative_drafts.id, creative_drafts.draft_version from")
    brief_lock = first(approve, "select recommendation_briefs.id from recommendation_briefs")
    brief_read = first(approve, "select approvals.decision from approvals")
    seq = next(i for i, q in enumerate(approve) if "max(approvals.decision_seq)" in q)
    assert member < draft_lock < brief_lock < brief_read < seq, approve
    if world.engine.dialect.name == "postgresql":
        assert approve[draft_lock].endswith("for no key update")
        assert approve[brief_lock].endswith("for key share")
    assert not [q for q in seen if q.startswith("select recommendation_briefs.id from")]


