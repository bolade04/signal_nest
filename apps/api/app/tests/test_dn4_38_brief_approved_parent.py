@dataclass
class World:
    engine: Engine
    factory: sessionmaker
    observer: Engine | None = None


def _world(engine: Engine, observer: Engine | None = None) -> Iterator[World]:
    Base.metadata.create_all(engine)
    factory = sessionmaker(bind=engine, expire_on_commit=False, future=True)
    with factory() as s:
        _seed(s)
    try:
        yield World(engine, factory, observer)
    finally:
        engine.dispose()
        if observer is not None:
            observer.dispose()


