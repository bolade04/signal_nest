def _decide_brief(s: Session, brief_id: str, decision: ApprovalDecision) -> Approval:
    """A decision on the brief by another reviewer, through the 5B service."""
    brief = s.get(RecommendationBrief, brief_id)
    return svc.record_decision(
        s, ctx=_ctx(s, OTHER), brief=brief, decision=decision,
        subject_version=brief.brief_version, reason_code=REASON[decision],
    )


def _decide_draft(s: Session, draft_id: str, decision: ApprovalDecision) -> Approval:
    draft = s.get(CreativeDraft, draft_id)
    return svc.record_draft_decision(
        s, ctx=_ctx(s, DECIDER), draft=draft, decision=decision,
        subject_version=draft.draft_version, reason_code=REASON[decision],
    )


