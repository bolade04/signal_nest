def _snapshot(w: World) -> dict[str, list[str]]:
    """Every row of the tables a decision could touch, each serialized whole (every column)."""
    out: dict[str, list[str]] = {}
    with w.engine.connect() as conn:
        for model in (Approval, AuditLog, RecommendationBrief, CreativeDraft, ContentReview):
            table = model.__table__
            out[table.name] = sorted(
                json.dumps(dict(r._mapping), default=str, sort_keys=True)
                for r in conn.execute(select(*table.c))
            )
    return out


def _draft_history(w: World, draft_id: str) -> list[tuple[str, int]]:
    with w.factory() as s:
        page = svc.list_draft_decisions(s, draft=s.get(CreativeDraft, draft_id))
        return [(a.decision, a.decision_seq) for a in page.items]


def _refused(w: World, draft_id: str) -> ConflictError:
    with w.factory() as s:
        with pytest.raises(ConflictError) as refused:
            _decide_draft(s, draft_id, APPROVED)
        s.rollback()
    return refused.value


def _assert_brief_not_approved(error: ConflictError) -> None:
    assert (error.status_code, error.code, error.message) == (
        409, "approval_review_blocked", BRIEF_NOT_APPROVED
    )


