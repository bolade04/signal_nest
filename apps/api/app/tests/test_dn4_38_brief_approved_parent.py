"""D-N4 item 38 (ruling 2026-11-12): a draft is approvable only while its brief is approved.

The ruling, verbatim: "preserve historical decisions while enforcing the approved-parent
requirement for new approvals. Explain downstream consequences explicitly." The adopted
recommendation it keeps: "A draft is approvable only while its brief's controlling decision on the
generated version is approved (refusal 409 approval_review_blocked, reason brief_not_approved);
existing approvals stand; Reject and Revoke stay allowed."

Before it (main ``6a3afe3a``) ``draft_approval_refusal`` read only the draft's own review and the
claims library, so a draft stayed approvable after its brief's approval was revoked or replaced by
a rejection, and while only another version of the brief was approved.

**Both engines** (the service, called exactly as the routes call it):

* an ``approved`` decision on a draft is refused 409 ``approval_review_blocked`` with the
  ``brief_not_approved`` sentence, writing nothing, while the brief version the draft was
  generated from has no decision, is rejected, was approved then rejected or revoked, or while
  only a newer or an older version of the brief is approved;
* it follows the brief version's *controlling* decision: refused, allowed once approved, refused
  once revoked, allowed once approved again, refused once rejected;
* rejecting a draft and revoking its standing approval stay allowed in every refused state;
* an approval recorded while the brief was approved stands when the brief is later revoked: every
  row recorded before is byte-equal afterwards, the drafts view still lists it as the controlling
  decision, and only a *new* approval is refused (as is what the 5E export will ask,
  ``draft_approval_refusal``, interface sheet P6);
* the statement order: the draft row lock, then the brief row lock, then the brief's controlling
  decision, then the sequence read; a rejection takes no brief lock.

**PostgreSQL** (``TEST_POSTGRES_URL``; unset FAILS in CI and skips elsewhere), real sessions in real
threads, every wait bounded:

* a revocation of the brief that comes first: the approval waits on the brief row (``FOR KEY
  SHARE`` blocked by the revocation), then reads the committed revocation and is refused;
* an approval that comes first: the revocation waits on the brief row the approval holds, and
  commits only after the approval has; no approved draft decision is written after it;
* the lock order does not deadlock with the paths that lock a brief and a draft (``Lock order`` in
  ``app.approvals.service``): generation of a revision of the draft being approved, the opportunity
  retention purge (it deletes the draft before the brief), and account erasure (it updates the
  brief before the draft);
* the lock statements compile to ``FOR NO KEY UPDATE`` (the draft) and ``FOR KEY SHARE`` (the
  brief).

**HTTP** (SQLite): a draft generated by the worker from an approved brief, whose brief is then
revoked, is refused 409 through the route; rejecting it is recorded; once the brief is approved
again the draft is approved.
"""

