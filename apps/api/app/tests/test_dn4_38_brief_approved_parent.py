@pytest.mark.parametrize("state", sorted(REFUSED))
def test_a_draft_approval_is_refused_while_its_brief_version_is_not_approved(world: World, state):
    draft_id, steps = REFUSED[state]
    _commit_brief_decisions(world, steps)
    before = _snapshot(world)
    _assert_brief_not_approved(_refused(world, draft_id))
    assert _snapshot(world) == before  # nothing written: no approval, no audit row
    with world.factory() as s:
        assert draft_approval_refusal(s, s.get(CreativeDraft, draft_id)) == "brief_not_approved"


def test_the_approval_follows_the_brief_versions_controlling_decision(world: World):
    """Refused with no decision; allowed once approved; refused once revoked; allowed once
    approved again; refused once rejected. History plays no part: the latest decision does."""
    outcomes = []
    for step in (None, (BRIEF1, APPROVED), (BRIEF1, REVOKED), (BRIEF1, APPROVED),
                 (BRIEF1, REJECTED)):
        if step is not None:
            _commit_brief_decisions(world, (step,))
        with world.factory() as s:
            try:
                approval = _decide_draft(s, DRAFT1, APPROVED)
            except ConflictError as exc:
                s.rollback()
                outcomes.append(("refused", exc.code, exc.message))
            else:
                s.commit()
                outcomes.append(("approved", approval.decision_seq))
    refused = ("refused", "approval_review_blocked", BRIEF_NOT_APPROVED)
    assert outcomes == [refused, ("approved", 1), refused, ("approved", 2), refused]
    assert _draft_history(world, DRAFT1) == [("approved", 2), ("approved", 1)]
    assert _draft_history(world, DRAFT2) == []  # the other version's draft is untouched


